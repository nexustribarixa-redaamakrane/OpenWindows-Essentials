bootvid_status_t bootvid_progress_bar(bootvid_context_t *ctx, uint32_t row, uint32_t col, uint32_t width, uint8_t progress, uint32_t fg, uint32_t bg)
{
    if (!ctx) return BOOTVID_ERR_NULL_POINTER;
    if (!ctx->initialized) return BOOTVID_ERR_NOT_INIT;
    if (width < 2) return BOOTVID_ERR_INVALID_POS;
    bootvid_putchar(ctx, row, col, '[', fg, bg);
    uint32_t inner = width - 2;
    uint32_t filled = ((uint32_t)progress * inner) / 255;
    for (uint32_t i = 0; i < inner; i++) {
        char c = (i < filled) ? '=' : ' ';
        bootvid_putchar(ctx, row, col + 1 + i, c, fg, bg);
    }
    bootvid_putchar(ctx, row, col + 1 + (inner > 0 ? inner - 1 : 0), '>', fg, bg);
    bootvid_putchar(ctx, row, col + width - 1, ']', fg, bg);
    return BOOTVID_OK;
}

bootvid_status_t bootvid_panic_screen(bootvid_context_t *ctx, const char *message)
{
    if (!ctx) return BOOTVID_ERR_NULL_POINTER;
    if (!ctx->initialized) return BOOTVID_ERR_NOT_INIT;
    return bootvid_panic_screen_sucs(ctx, (const uint8_t *)message);
}

static uint32_t sutf8_codepoint_count(const uint8_t *sutf8)
{
    uint32_t count = 0;
    const uint8_t *p = sutf8;
    while (p && *p) {
        sucs_char_t cp;
        size_t adv = sutf8_next_codepoint(p, 6, &cp);
        if (adv == 0) break;
        p += adv;
        count++;
    }
    return count;
}

bootvid_status_t bootvid_panic_screen_sucs(bootvid_context_t *ctx, const uint8_t *sutf8_message)
{
    if (!ctx) return BOOTVID_ERR_NULL_POINTER;
    if (!ctx->initialized) return BOOTVID_ERR_NOT_INIT;
    bootvid_clear(ctx, BOOTVID_COLOR_RED);
    const uint8_t banner[] = "SYSTEM PANIC";
    uint32_t banner_len = sutf8_codepoint_count(banner);
    uint32_t banner_col = (ctx->max_cols > banner_len) ? (ctx->max_cols - banner_len) / 2 : 0;
    uint32_t banner_row = ctx->max_rows / 2;
    bootvid_puts_sucs(ctx, banner_row, banner_col, banner, BOOTVID_COLOR_WHITE, BOOTVID_COLOR_RED);
    if (sutf8_message) {
        uint32_t msg_len = sutf8_codepoint_count(sutf8_message);
        uint32_t msg_col = (ctx->max_cols > msg_len) ? (ctx->max_cols - msg_len) / 2 : 0;
        uint32_t msg_row = banner_row + 2;
        if (msg_row < ctx->max_rows) {
            bootvid_puts_sucs(ctx, msg_row, msg_col, sutf8_message, BOOTVID_COLOR_YELLOW, BOOTVID_COLOR_RED);
        }
    }
    return BOOTVID_OK;
}
