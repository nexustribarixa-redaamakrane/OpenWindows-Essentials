static void bootvid_put_pixel(bootvid_context_t *ctx, uint32_t row, uint32_t col, uint32_t color)
{
    if (row >= ctx->height || col >= ctx->width) return;
    uint32_t offset = row * ctx->pitch + col * 4;
    uint32_t *pixel = (uint32_t *)((uint8_t *)ctx->framebuffer + offset);
    *pixel = color;
}

static void bootvid_putchar_raw(bootvid_context_t *ctx, uint32_t px_row, uint32_t px_col, sucs_char_t cp, uint32_t fg, uint32_t bg)
{
    int idx;
    if (cp >= 0x20u && cp <= 0x7Eu)
        idx = (int)cp - 0x20;
    else
        idx = 0;  /* SUCS codepoint outside glyph subset renders blank */
    const uint8_t *glyph = bootvid_font[idx];
    for (uint32_t y = 0; y < FONT_H; y++) {
        uint8_t bits = glyph[y];
        for (uint32_t x = 0; x < FONT_W; x++) {
            uint32_t color = (bits & 0x80) ? fg : bg;
            bootvid_put_pixel(ctx, px_row + y, px_col + x, color);
            bits <<= 1;
        }
    }
}

bootvid_status_t bootvid_init(bootvid_context_t *ctx, void *framebuffer, uint32_t width, uint32_t height, uint32_t pitch)
{
    if (!ctx) return BOOTVID_ERR_NULL_POINTER;
    if (!framebuffer) return BOOTVID_ERR_NULL_POINTER;
    ctx->framebuffer  = framebuffer;
    ctx->width        = width;
    ctx->height       = height;
    ctx->pitch        = pitch;
    ctx->pixel_format = PIXELFORMAT_RGBX32;
    ctx->max_rows     = height / FONT_H;
    ctx->max_cols     = width / FONT_W;
    ctx->text_fg      = BOOTVID_COLOR_WHITE;
    ctx->text_bg      = BOOTVID_COLOR_BLACK;
    ctx->cursor_row   = 0;
    ctx->cursor_col   = 0;
    ctx->initialized  = true;
    return BOOTVID_OK;
}

